import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {transform} from 'esbuild';
const code=await transform(await readFile(new URL('../lib/work-order-match.ts',import.meta.url),'utf8'),{loader:'ts',format:'esm'});
const {matchAssets,assetWords,sourceOperationId}=await import('data:text/javascript;base64,'+Buffer.from(code.code).toString('base64'));
const silver={id:'silver',name:'Silver Streak',number:''},bolt={id:'bolt',name:'Lightning Bolt',number:''};
assert.deepEqual(matchAssets('The SILVER STREAK lamp is out.',[silver]),[silver]);
assert.deepEqual(matchAssets('Silver Streaker lamp is out.',[silver]),[]);
assert.deepEqual(matchAssets('Silver lamp is out.',[silver]),[]);
assert.deepEqual(matchAssets('Silver-Streak lamp is out.',[silver]),[silver]);
assert.equal(matchAssets('Silver Streak and Lightning Bolt have problems.',[silver,bolt]).length,2);
assert.equal(matchAssets('Silver Streak lamp issue.',[silver,{...silver,id:'other'}]).length,2);
assert.equal(matchAssets('Silver Streak lamp issue.',[silver,silver]).length,1);
assert.equal(assetWords('The lamp on Silver Streak is out').complete,true);
assert.equal(assetWords(Array.from({length:17},(_,i)=>'word'+i).join(' ')).complete,false);
const first=await sourceOperationId('main:alice:post1','request');
assert.equal(first,await sourceOperationId('main:alice:post1','request'));
assert.notEqual(first,await sourceOperationId('main:alice:post1','photo'));
assert.notEqual(first,await sourceOperationId('other:alice:post1','request'));
assert.match(first,/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
console.log('Passed 13 name matching, ambiguity, and duplicate prevention checks.');
